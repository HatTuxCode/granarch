#!/usr/bin/env python3
"""Generate app colors from Gran's resolved palette after theme changes."""
from pathlib import Path
import configparser
import re
import subprocess
from datetime import datetime
import shutil
import os
import json

home = Path.home()
config = home / '.config'
palette = dict(line.split('\t', 1) for line in subprocess.check_output(
    ['gran-theme-color', '--all'], text=True).splitlines() if '\t' in line)
def color(key):
    value = palette[key]
    if not re.fullmatch(r'#[0-9a-fA-F]{6}', value):
        raise ValueError(f'Invalid color {key}: {value}')
    return value
bg, fg, accent = (color(k) for k in ('background', 'foreground', 'accent'))
sidebar, raised, selection = (color(k) for k in ('dark_background', 'lighter_background', 'selection'))
muted = color('light_foreground')
stamp = datetime.now().strftime('%Y%m%d-%H%M%S')
def write(path, content, backup=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == content:
        return
    if backup and path.exists():
        shutil.copy2(path, path.with_name(path.name + '.bak.gran-colors.' + stamp))
    temporary = path.with_name(path.name + '.gran-tmp')
    temporary.write_text(content)
    temporary.replace(path)

zen = f'''/* Generated by the Gran theme-set hook. */
:root {{
  --zen-primary-color: {accent} !important;
  --zen-main-browser-background: {bg} !important;
  --zen-colors-primary: {bg} !important;
  --zen-colors-secondary: {sidebar} !important;
  --zen-colors-tertiary: {raised} !important;
  --zen-colors-border: {selection} !important;
  --zen-colors-hover-bg: {raised} !important;
  --zen-colors-input-bg: {raised} !important;
  --zen-colors-input-border: {selection} !important;
  --zen-colors-input-text: {fg} !important;
  --zen-colors-text: {fg} !important;
  --zen-urlbar-background-base: {raised} !important;
  --toolbar-bgcolor: {bg} !important;
  --toolbar-color: {fg} !important;
  --toolbar-field-background-color: {raised} !important;
  --toolbar-field-color: {fg} !important;
  --toolbar-field-focus-background-color: {sidebar} !important;
  --toolbar-field-focus-color: {fg} !important;
  --lwt-accent-color: {bg} !important;
  --lwt-text-color: {fg} !important;
  --lwt-sidebar-background-color: {sidebar} !important;
  --lwt-sidebar-text-color: {fg} !important;
  --arrowpanel-background: {raised} !important;
  --arrowpanel-color: {fg} !important;
  --arrowpanel-border-color: {selection} !important;
  --tab-selected-bgcolor: {selection} !important;
  --tab-selected-textcolor: {fg} !important;
  --link-color: {accent} !important;
}}
/* Inherit the base size; preserve native heading and caption proportions. */
#main-window, #zen-main-app-wrapper {{ background: {bg} !important; color: {fg} !important; }}
#navigator-toolbox {{ background: {sidebar} !important; color: {fg} !important; }}
/* Zen writes theme variables on its background elements, not only :root. */
.zen-browser-generic-background {{
  --zen-main-browser-background: {bg} !important;
  --zen-main-browser-background-old: {bg} !important;
  --zen-main-browser-background-toolbar: {sidebar} !important;
  --zen-main-browser-background-toolbar-old: {sidebar} !important;
  --zen-background-opacity: 1 !important;
}}
.zen-browser-generic-background::after {{ background: {bg} !important; opacity: 1 !important; }}
.zen-browser-generic-background::before {{ opacity: 0 !important; }}
.zen-browser-generic-background.zen-toolbar-background::after {{ background: {sidebar} !important; }}
#navigator-toolbox, #zen-sidebar-top-buttons, #zen-sidebar-foot-buttons {{
  --toolbar-color: {fg} !important;
  --lwt-text-color: {fg} !important;
  --zen-colors-text: {fg} !important;
}}

'''
reference = home / '.local/share/gran/default/zen/reference.json'
preferences = json.loads(reference.read_text())['preferences'] if reference.exists() else {}
preferences.update({'toolkit.legacyUserProfileCustomizations.stylesheets': True, 'browser.theme.toolbar-theme': 0, 'browser.theme.content-theme': 0})
ini = Path(os.environ.get('GRAN_ZEN_INI', str(config / 'zen/profiles.ini')))
if ini.exists():
    profiles = configparser.ConfigParser()
    profiles.read(ini)
    for section in profiles.sections():
        if not section.startswith('Profile'):
            continue
        relative = profiles.getboolean(section, 'IsRelative', fallback=True)
        value = profiles.get(section, 'Path')
        profile = ini.parent / value if relative else Path(value)
        # A placeholder profile has no initialized preferences yet.
        write(profile / 'chrome/gran-colors.css', zen)
        content = f'''/* Only browser home pages; website colors remain their own. */
@-moz-document url("about:newtab"), url("about:home"), url("about:blank") {{
  :root {{
    --newtab-background-color: {bg} !important;
    --newtab-text-primary-color: {fg} !important;
    --newtab-text-secondary-color: {muted} !important;
    --newtab-element-secondary-color: {raised} !important;
    --newtab-primary-action-background: {accent} !important;
  }}
  html, body {{ background-color: {bg} !important; color: {fg} !important; }}
}}
'''
        write(profile / 'chrome/gran-content.css', content)
        content_entry = profile / 'chrome/userContent.css'
        previous = content_entry.read_text() if content_entry.exists() else ''
        content_import = '@import url("gran-content.css");'
        if content_import not in previous:
            write(content_entry, content_import + '\n' + previous, backup=True)

        entry = profile / 'chrome/userChrome.css'
        existing = entry.read_text() if entry.exists() else ''
        line = '@import url("gran-colors.css");'
        if line not in existing:
            write(entry, line + '\n' + existing, backup=True)
        entry = profile / 'user.js'
        existing = entry.read_text() if entry.exists() else ''
        for key, value in preferences.items():
            existing = re.sub(r'^user_pref\("' + re.escape(key) + r'",.*\);\n?', '', existing, flags=re.M)
            pref = 'user_pref(' + json.dumps(key) + ', ' + json.dumps(value) + ');'
            existing = existing.rstrip() + '\n' + pref + '\n'
        write(entry, existing, backup=True)
print('Zen palette generated:', bg, fg, accent)

# One palette source for both browser integrations. A system path unit installs this policy.
write(home / '.local/state/gran/chromium-color.json', json.dumps({
    'BrowserThemeColor': accent, 'BrowserColorScheme': 'light' if palette.get('mode') == 'light' else 'dark'
}) + '\n')
# Policy file updates trigger Chromium's own policy directory watcher.
